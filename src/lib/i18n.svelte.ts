function readInitial(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch {}
  return "zh";
}

// Initialised from storage at module load (client-only; falls back to zh during build/SSR), so the
// first paint is already in the chosen language — no zh→en flash.
let current = $state<Lang>(readInitial());

/** Re-read the saved language (safe to call again after mount). */
export function initLang() {
  current = readInitial();
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {}
}

export function toggleLang() {
  setLang(current === "zh" ? "en" : "zh");
}

/** Translate a key (reactive: re-runs when the language changes). `{name}` placeholders are filled
 *  from `params`. Unknown keys return the key; missing translations fall back to Chinese. */
export function t(key: string, params?: Record<string, string | number>): string {
  const entry = dict[key];
  let s = entry ? entry[current] ?? entry.zh : key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}
